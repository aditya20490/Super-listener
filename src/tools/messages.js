function hash(s) {
  // small stable hash (djb2), base 36
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36);
}

let cache = null;

// Every general line, once. cat: morning | afternoon | evening | night | weekend | away | any | mix
export function allMessages() {
  if (cache) return cache;
  const seen = new Set();
  const out = [];
  const add = (text, cat) => {
    const key = text.trim();
    if (!key || seen.has(key)) return;
    seen.add(key);
    out.push({ id: hash(key), cat: cat, text: key });
  };
  for (const cat of Object.keys(BY_TIME)) for (const t of BY_TIME[cat]) add(t, cat);
  for (const t of ANY) add(t, 'any');
  for (const o of OPENERS) for (const c of CLOSERS) add(o + ' ' + c, 'mix');
  cache = out;
  return out;
}

export function personalMessages() {
  return PERSONAL.map((t) => ({ id: 'p' + hash(t), cat: 'personal', text: t }));
}

// Fills a personal line. Returns null if a value it needs is missing.
export function fill(text, vars) {
  let missing = false;
  const s = text.replace(/\{(\w+)\}/g, (m, k) => {
    const v = vars ? vars[k] : undefined;
    if (v === undefined || v === null || v === '') {
      missing = true;
      return '';
    }
    return String(v);
  });
  return missing ? null : s;
}

